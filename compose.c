{
	if (!gpf_resolve(font, id, decomp->draw_base, res))
		return 0;

	if (decomp->draw_base == decomp->base_code)
		return 1;

	/* few fonts have ı and fewer ȷ, the letter with its dot taken off is */
	if (gpf_resolve(font, id, decomp->base_code, res))
		return 1;

	if (remove_dot(&res->glyph)) {
		gpf_resolved_clear(res);
		return 1;
	}

	return 0;
}

/*
 * The accent as this font draws it, taken off a letter that carries it: the
 * caron is `Č` minus `C`.  Any letter with the same accent will do, and the
 * first one that gives a clean subtraction is used — the base has to sit
 * inside it pixel for pixel, so a letter whose accent touches its base is
 * rejected rather than mangled.
 */
static int accent_from_letter(struct gpf_font *font, enum gpf_variant_id id,
                              const struct gpf_decomposition *decomp,
                              struct gpf_glyph *out)
{
	unsigned int i;

	for (i = 0; gpf_decompositions[i].code; i++) {
		struct gpf_resolved letter = {0}, base = {0};
		int ret;

		if (gpf_decompositions[i].mark != decomp->mark)
			continue;

		if (gpf_decompositions[i].code == decomp->code)
			continue;

		if (gpf_resolve(font, id, gpf_decompositions[i].code, &letter))
			continue;

		if (gpf_draw_base(font, id, &gpf_decompositions[i], &base)) {
			gpf_resolved_clear(&letter);
			continue;
		}

		ret = gpf_compose_remainder(&letter.glyph, &base.glyph, out);

		gpf_resolved_clear(&letter);
		gpf_resolved_clear(&base);

		if (!ret)
			return 0;
	}

	return 1;
}

int gpf_accent_ink(struct gpf_font *font, enum gpf_variant_id id,
                   const struct gpf_decomposition *decomp,
                   struct gpf_glyph *out)
{
	uint32_t codes[2] = {decomp->mark, decomp->accent};
	unsigned int i;

	memset(out, 0, sizeof(*out));

	if (!accent_from_letter(font, id, decomp, out))
		return 0;

	/* no letter to take it from: the mark, and then the spacing accent */
	for (i = 0; i < 2; i++) {
		struct gpf_resolved res = {0};

		if (!codes[i] || gpf_resolve(font, id, codes[i], &res))
			continue;

		*out = res.glyph;

		/* the ink is handed over, not copied */
		res.glyph.bits = NULL;

		gpf_resolved_clear(&res);

		return 0;
	}

	return 1;
}
